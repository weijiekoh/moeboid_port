#!/usr/bin/env python3
"""Cursor resources of ZapSpot.exe to PNG images and hotspots for the web host (M5b).

Source: the resource pack (port/build/web/pack.bin, built by mkpack.py): zap/GROUP_CURSOR/<NAME>.CUR gives
the resource id of the cursor image, zap/CURSOR/<id> = hotspot (u16 x, u16 y), BITMAPINFOHEADER (height =
2 x 32), 2-colour table, XOR mask, AND mask (rows bottom-up, 4 bytes per row).
Order = the cursor manager (Z:0x425a80, analysis/rendering.md 8; port_cursor() ids 0..5):
  0 POINTER, 1 HAND, 2 NOLINK, 3 OPENHAND, 4 CLOSEDHAND, 5 HOURGLASS.
Pixel rule (Windows monochrome cursor): AND 0 XOR 0 black, AND 0 XOR 1 white, AND 1 XOR 0 transparent,
AND 1 XOR 1 inverts the screen. CSS cursors cannot invert; such pixels become opaque black (approximation,
reported per cursor).

Output: port/build/cursors/<NAME>.png (32 x 32 RGBA, deterministic PNG) and the TypeScript block of
port/host/main.ts between the lines "// BEGIN CURSORS" and "// END CURSORS" (CSS `url(data:...) x y`).
  python -I -B port/tools/mkcursors.py              write the PNGs, print the block
  python -I -B port/tools/mkcursors.py --update     also rewrite the block in port/host/main.ts
  python -I -B port/tools/mkcursors.py --check      exit 1 when main.ts holds another block
Options: --pack PATH (default port/build/web/pack.bin).
"""
import base64
import os
import struct
import sys
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
NAMES = ['POINTER', 'HAND', 'NOLINK', 'OPENHAND', 'CLOSEDHAND', 'HOURGLASS']
MAIN_TS = os.path.join(ROOT, 'port/host/main.ts')
BEGIN, END = '// BEGIN CURSORS', '// END CURSORS'


def read_pack(path):
    d = open(path, 'rb').read()
    if d[:4] != b'MPAK':
        raise SystemExit('mkcursors: %s is not a resource pack' % path)
    _, n = struct.unpack_from('<II', d, 4)
    p, out = 12, {}
    for _ in range(n):
        ln, = struct.unpack_from('<I', d, p)
        name = d[p + 4:p + 4 + ln].decode('ascii')
        off, sz = struct.unpack_from('<II', d, p + 4 + ln)
        out[name] = d[off:off + sz]
        p += 12 + ln
    return out


def cursor_rgba(res):
    """RT_CURSOR resource -> (width, height, hotspot x, hotspot y, RGBA bytes, inverted pixel count)."""
    hx, hy = struct.unpack_from('<HH', res, 0)
    bi = 4
    size, w, h2, planes, bpp = struct.unpack_from('<IiiHH', res, bi)
    if bpp != 1 or planes != 1:
        raise SystemExit('mkcursors: %d bpp cursors are not supported' % bpp)
    h = h2 // 2
    ncol, = struct.unpack_from('<I', res, bi + 32)
    pal = bi + size
    bits = pal + 4 * (ncol or 2)
    stride = ((w + 31) // 32) * 4
    xor, andm = bits, bits + stride * h
    rgba, inv = bytearray(), 0
    for y in range(h):
        row = h - 1 - y  # bottom-up
        for x in range(w):
            sh = 7 - (x & 7)
            a = (res[andm + row * stride + (x >> 3)] >> sh) & 1
            c = (res[xor + row * stride + (x >> 3)] >> sh) & 1
            b, g, r, _ = res[pal + 4 * c:pal + 4 * c + 4]
            if a and not c:
                rgba += b'\0\0\0\0'
            elif a:
                inv += 1
                rgba += b'\0\0\0\xff'
            else:
                rgba += bytes((r, g, b, 255))
    return w, h, hx, hy, bytes(rgba), inv


def png(w, h, rgba):
    def chunk(t, data):
        return struct.pack('>I', len(data)) + t + data + struct.pack('>I', zlib.crc32(t + data) & 0xffffffff)
    raw = b''.join(b'\0' + rgba[4 * w * y:4 * w * (y + 1)] for y in range(h))
    return (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 6, 0, 0, 0)) +
            chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))


def build(pack_path):
    pack = read_pack(pack_path)
    out, info = [], []
    for name in NAMES:
        grp = pack.get('zap/GROUP_CURSOR/%s.CUR' % name)
        if grp is None:
            raise SystemExit('mkcursors: zap/GROUP_CURSOR/%s.CUR missing in %s' % (name, pack_path))
        _, typ, count = struct.unpack_from('<HHH', grp, 0)
        rid, = struct.unpack_from('<H', grp, 6 + 12)  # first entry: w, h, planes, bpp (u16 x 4), bytes (u32), id
        w, h, hx, hy, rgba, inv = cursor_rgba(pack['zap/CURSOR/%d' % rid])
        out.append((name, w, h, hx, hy, png(w, h, rgba)))
        info.append('%s: resource %d, %dx%d, hotspot (%d, %d), inverting pixels %d' % (name, rid, w, h, hx, hy, inv))
    return out, info


def ts_block(cursors):
    lines = [BEGIN + ' (generated by port/tools/mkcursors.py from the ZapSpot.exe cursor resources)',
             '// CSS cursor per port_cursor() id: 0..5 = cursor manager order (Z:0x425a80, rendering.md 8);',
             '// 6, 7 = arrow and I-beam of the modal dialogs (system cursors: CSS placeholders, no XP cursor file).',
             'const CURSORS: readonly string[] = [']
    for name, w, h, hx, hy, data in cursors:
        uri = 'data:image/png;base64,' + base64.b64encode(data).decode('ascii')
        lines.append('  `url("%s") %d %d, default`, // %s' % (uri, hx, hy, name))
    lines += ['  "default", // 6 IDC_ARROW (placeholder)', '  "text", // 7 IDC_IBEAM (placeholder)', '];', END]
    return '\n'.join(lines)


def replace_block(text, block):
    a, b = text.find(BEGIN), text.find(END)
    if a < 0 or b < a:
        raise SystemExit('mkcursors: markers %s / %s missing in %s' % (BEGIN, END, MAIN_TS))
    return text[:a] + block + text[b + len(END):]


def main(argv):
    pack = os.path.join(ROOT, 'port/build/web/pack.bin')
    if '--pack' in argv:
        pack = argv[argv.index('--pack') + 1]
    cursors, info = build(pack)
    odir = os.path.join(ROOT, 'port/build/cursors')
    os.makedirs(odir, exist_ok=True)
    for name, w, h, hx, hy, data in cursors:
        with open(os.path.join(odir, name + '.png'), 'wb') as f:
            f.write(data)
    block = ts_block(cursors)
    for line in info:
        print('mkcursors: ' + line)
    text = open(MAIN_TS).read()
    if '--check' in argv:
        same = replace_block(text, block) == text
        print('mkcursors: main.ts cursor block %s' % ('up to date' if same else 'differs (run --update)'))
        return 0 if same else 1
    if '--update' in argv:
        new = replace_block(text, block)
        if new != text:
            with open(MAIN_TS, 'w') as f:
                f.write(new)
        print('mkcursors: main.ts cursor block %s' % ('written' if new != text else 'unchanged'))
    else:
        print(block)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
