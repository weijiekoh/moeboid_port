"""Generate port/src/cpu/fsin_table.h from an x87 FSIN/FCOS table (decisions.md item 11: the
reference values are provisional; to replace them, run this script on another table file of the
same format and rebuild, or install a table at run time with cpu_set_fsin_table()).

Input format (analysis/verification/fpu/x87_fsin_table.tsv, written by fsin_check.c): header line,
then one line per argument: k, angle, FSIN(angle), FCOS(angle); each 80-bit value as
SIGN_EXPONENT:SIGNIFICAND in hex. Rows must be sorted by angle (ascending, angles >= 0).

Usage: python -I -B gen_fsin_table.py [TABLE.tsv [OUT.h]]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_IN = os.path.join(HERE, "..", "..", "..", "analysis", "verification", "fpu", "x87_fsin_table.tsv")
DEFAULT_OUT = os.path.join(HERE, "fsin_table.h")


def parse(path):
    rows = []
    for i, line in enumerate(open(path)):
        if i == 0:
            continue
        f = line.split()
        vals = []
        for col in f[1:4]:
            e, m = col.split(":")
            vals.append((int(e, 16), int(m, 16)))
        rows.append(vals)
    keys = [(a[0], a[1]) for a, _, _ in rows]
    if any(k[0] & 0x8000 for k in keys) or keys != sorted(keys) or len(set(keys)) != len(keys):
        raise SystemExit("table arguments must be >= 0, unique and sorted")
    return rows


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_IN
    out = sys.argv[2] if len(sys.argv) > 2 else DEFAULT_OUT
    rows = parse(src)
    lines = [
        "/* x87 FSIN/FCOS table (80-bit results measured on an Intel i7-13700HX, verification.md 3.1).",
        f" * Generated by port/src/cpu/gen_fsin_table.py from {os.path.basename(src)}. Do not edit.",
        " * Replaceable (decisions.md item 11): regenerate from another table file of the same format.",
        " * Fields: arg_m, sin_m, cos_m, arg_se, sin_se, cos_se (significand, sign/exponent). */",
        "#ifndef MOEBOID_CPU_FSIN_TABLE_H",
        "#define MOEBOID_CPU_FSIN_TABLE_H",
        f"#define CPU_FSIN_TABLE_N {len(rows)}u",
        "static const CpuFsinEntry cpu_fsin_table_default[CPU_FSIN_TABLE_N] = {",
    ]
    for a, s, c in rows:
        lines.append(f"    {{0x{a[1]:016x}ull, 0x{s[1]:016x}ull, 0x{c[1]:016x}ull, 0x{a[0]:04x}, 0x{s[0]:04x}, 0x{c[0]:04x}}},")
    lines += ["};", "#endif", ""]
    with open(out, "w") as f:
        f.write("\n".join(lines))
    print(f"{out}: {len(rows)} entries")


if __name__ == "__main__":
    main()
